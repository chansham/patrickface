import assert from 'node:assert/strict';
import { STAGE, normalizeClip, sourceRect, destinationRect, frameAt, IdleScheduler, restoreEvents, bedtimeRemaining, automaticAllowed, reviewKey, cleanReview } from './player-core.js';
const raw = { id: 'blink', title: 'Blink', version: 2, sha256: 'a'.repeat(64), atlas: 'test.png', columns: 4, rows: 2, frameCount: 8, width: 1774, height: 887, durationsMs: Array(8).fill(100), scenes: ['awake'], triggerKinds: ['idle'] };
const clip = normalizeClip(raw);
assert.deepEqual(sourceRect(clip, 0), [0, 0, 443.5, 443.5]);
for (let i = 0; i < 8; i++) {
 const rect = sourceRect(clip, i); assert.deepEqual(rect.slice(2), [443.5,443.5]);
 destinationRect(clip).forEach((value, index) => assert.ok(Math.abs(value - [83.2, 248, 665.6, 665.6][index]) < 1e-9));
 assert.ok(destinationRect(clip)[1] >= STAGE.safeTop);
 assert.ok(destinationRect(clip)[1] + destinationRect(clip)[3] <= STAGE.safeBottom);
}
const double = normalizeClip({ ...raw, id: 'double', frameCount: 16, frameIndices: [...Array(8).keys(), ...Array(8).keys()], durationsMs: Array(16).fill(100) });
const anchored = destinationRect({ ...clip, scale: 0.85, anchorNormalized: [0.52, 0.92] }, { anchorNormalized: [0.5, 0.88] });
assert.ok(Math.abs(anchored[0] + anchored[2] * 0.52 - (STAGE.x + STAGE.size * 0.5)) < 1e-9);
assert.ok(Math.abs(anchored[1] + anchored[3] * 0.92 - (STAGE.y + STAGE.size * 0.88)) < 1e-9, 'different clips share the same master anchor without per-frame fitting');
assert.deepEqual(sourceRect(double, 8), sourceRect(double, 0));
assert.deepEqual(sourceRect(double, 15), sourceRect(double, 7));
assert.equal(frameAt(double, 800), 8); assert.equal(frameAt(double, 1600), 15);
assert.throws(() => normalizeClip({ ...raw, frameCount: 9, durationsMs: Array(9).fill(100) }), /來源格/);
assert.throws(() => normalizeClip({ ...raw, durationsMs: Array(8).fill(0) }), /每格時間/);
assert.equal(normalizeClip({ id: 'pending' }).available, false);
const options = [{ id: 'normal' }, { id: 'slow' }, { id: 'double' }];
const idle = new IdleScheduler(() => 0);
const enabled = { eligible: true, playing: false, clips: options };
assert.equal(idle.step(0, enabled), null); assert.equal(idle.nextAt, 10000);
assert.equal(idle.step(9999, enabled), null); assert.equal(idle.step(10000, enabled).id, 'normal');
assert.equal(idle.step(11000, enabled), null); assert.equal(idle.step(21000, enabled).id, 'slow');
assert.equal(idle.step(22000, { ...enabled, playing: true }), null); assert.equal(idle.nextAt, null);
assert.equal(idle.step(80000, enabled), null); assert.equal(idle.nextAt, 90000, 'interaction completion begins a new wait');
assert.equal(idle.step(85000, { ...enabled, eligible: false }), null);
assert.equal(idle.step(900000, enabled), null); assert.equal(idle.nextAt, 910000, 'return never catches up old idle deadlines');
const maximum = new IdleScheduler(() => 1); maximum.step(10, enabled); assert.equal(maximum.nextAt, 22010);
const single = new IdleScheduler(() => 0); const one = { ...enabled, clips: options.slice(0,1) }; single.step(0, one); single.step(10000, one); single.step(11000, one); assert.equal(single.step(21000, one), null, 'one available idle cannot repeat consecutively');
const active = { enabled: true, hidden: false, reduced: false, wristDown: false, lowPower: false, reviewing: false };
assert.equal(automaticAllowed(active), true);
for (const key of ['hidden','reduced','wristDown','lowPower','reviewing']) assert.equal(automaticAllowed({ ...active, [key]: true }), false, key);
assert.equal(automaticAllowed({ ...active, enabled: false }), false);
assert.equal(bedtimeRemaining(restoreEvents(null, 1000000), 1000000), 0);
const event = restoreEvents({ bedtimeLastAt: 1000000 }, 1000000);
assert.equal(bedtimeRemaining(event, 1599999), 1); assert.equal(bedtimeRemaining(event, 1600000), 0);
assert.equal(bedtimeRemaining(restoreEvents({ bedtimeLastAt: 1000000 }, 900000), 900000), 600000, 'clock rollback cannot defeat the cooldown');
assert.equal(bedtimeRemaining(restoreEvents({ bedtimeLastAt: NaN }, 1), 1), 0);
const old = { version: 2, sha256: clip.sha256, frames: { 0: 'liked', 9: 'rejected' }, note: 'existing comment' };
const restored = cleanReview(old, clip); assert.deepEqual(restored.sections.action.frames, { 0: 'liked' }); assert.equal(restored.sections.action.note, old.note);
assert.notEqual(reviewKey(clip), reviewKey({ ...clip, sha256: 'b'.repeat(64) }));
assert.deepEqual(cleanReview(old, { ...clip, sha256: 'b'.repeat(64) }).sections.action.frames, {});
restored.sections.outfit.note = 'outfit only'; assert.equal(restored.sections.action.note, old.note);
console.log('PASS: fixed fractional cells, 16-frame sequences, stable safe layout, one-shot endpoints, idle timing/non-repeat, blocked/resume priority, cooldown/clock rollback, version/hash review isolation.');
