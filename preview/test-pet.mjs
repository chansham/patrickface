import assert from "node:assert/strict";
import { newPet, restorePet, dispatch, resolveScene, holidayFor, isSleepHour, idleAction } from "./pet-core.js";
const date = new Date(2026, 8, 27, 14, 0, 0);
const now = date.getTime();
let pet = newPet(now);
assert.equal(resolveScene(pet, {}, date).mode, "awake");
assert.equal(resolveScene(pet, { charging: true }, date).mode, "charging");
assert.equal(isSleepHour(0), true); assert.equal(isSleepHour(7), false);
assert.equal(isSleepHour(14, 12, 16), true); assert.equal(isSleepHour(12, 12, 12), false);
pet = dispatch(pet, { type: "timer", mode: "strength", seconds: 60 }, now);
assert.equal(resolveScene(pet, {}, new Date(now + 59000)).remaining, 1);
assert.equal(resolveScene(pet, {}, new Date(now + 60000)).mode, "celebrate");
assert.equal(resolveScene(pet, {}, new Date(now + 3600000)).activityComplete, true);
assert.equal(resolveScene(restorePet(pet, now + 3600000), {}, new Date(now + 3600000)).mode, "celebrate", "timer survives reload and absence");
pet = dispatch(pet, { type: "stop" }, now);
pet = dispatch(pet, { type: "feed" }, now);
pet = dispatch(pet, { type: "feed" }, now + 1000);
assert.equal(pet.fed, 1); assert.equal(pet.lastEvent.type, "full");
pet = dispatch(pet, { type: "feed" }, now + 3000); assert.equal(pet.fed, 2);
pet = dispatch(pet, { type: "nfc-bed" }, now);
assert.equal(resolveScene(pet, { charging: true }, date).mode, "sleeping");
assert.equal(resolveScene(pet, { reducedMotion: true }, date).subdued, true);
assert.equal(holidayFor(new Date(2026, 1, 17, 12)).id, "lunar-new-year");
assert.equal(holidayFor(new Date(2026, 8, 25, 12)).id, "mid-autumn");
assert.equal(holidayFor(new Date(2027, 1, 6, 12)).id, "lunar-new-year", "lunar dates vary each year");
assert.equal(holidayFor(new Date(2026, 11, 25), "12-25").id, "birthday");
assert.equal(holidayFor(new Date(2026, 4, 9)), null);
const clean = restorePet({ version: 1, mode: "broken", fed: -42, activity: { endsAt: "no" }, recent: [1, "tap"] });
assert.equal(clean.mode, "auto"); assert.equal(clean.fed, 0); assert.equal(clean.activity, null); assert.deepEqual(clean.recent, ["tap"]);
assert.deepEqual(dispatch(pet, { type: "unsupported" }, now), pet);
let previous = "";
for (let i = 0; i < 20; i++) { const action = idleAction(i, previous); assert.notEqual(action, previous); previous = action; }
const bucket = Math.floor(now / 12000);
assert.equal(new Set(Array.from({ length: 20 }, (_, i) => idleAction(bucket + i))).size, 4);
pet = dispatch(pet, { type: "mood", value: "happy" }, now);
pet = dispatch(pet, { type: "mood", value: "" }, now);
assert.equal(restorePet(pet).mood, null);
pet = dispatch(pet, { type: "timer", mode: "focus", seconds: 1500 }, now);
assert.equal(resolveScene(pet, { now: now + 1000 }, new Date(2028, 0, 1)).remaining, 1499);
console.log("PASS: time/charging priority, lunar holidays, rest windows, persistent timers, input validation, feeding cooldown, varied idle.");
